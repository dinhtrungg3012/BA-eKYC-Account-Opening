USE MoTaiKhoan_eKYC;
GO

-- HoSoDangKy
CREATE TABLE dbo.HoSoDangKy
(
    MaHoSo INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    HoTen NVARCHAR(100) NULL,
    SoCCCD VARCHAR(12) NULL,
    NgaySinh DATE NULL,
    GioiTinh NVARCHAR(10) NULL,
    DiaChi NVARCHAR(255) NULL,
    NgayHetHanCCCD DATE NULL,
    SoDienThoai VARCHAR(10) NOT NULL,
    MaGioiThieu VARCHAR(20) NULL,
    DiemGiaoDich NVARCHAR(100) NULL,
    TrangThaiHoSo VARCHAR(30) NOT NULL DEFAULT ('DangThucHien'),
    DaXacThucSDT BIT NOT NULL DEFAULT (0),
    SoLanOTPSai TINYINT NOT NULL DEFAULT (0),
    KhoaOTPDen DATETIME2(3) NULL,
    SoLanThatBaiEKYC TINYINT NOT NULL DEFAULT (0),
    PhienBanCCCD INT NOT NULL DEFAULT (0),
    AnhMatTruocRef NVARCHAR(500) NULL,
    AnhMatSauRef NVARCHAR(500) NULL,
    DuLieuKhuonMatRef NVARCHAR(500) NULL,
    DaDatOCR BIT NOT NULL DEFAULT (0),
    XacNhanThongTinCCCD BIT NOT NULL DEFAULT (0),
    DaDatFace BIT NOT NULL DEFAULT (0),
    DaDatLiveness BIT NOT NULL DEFAULT (0),
    XacNhanDieuKhoan BIT NOT NULL DEFAULT (0),
    PhienBanDieuKhoan VARCHAR(20) NULL,
    ThoiDiemDongYDieuKhoan DATETIME2(3) NULL,
    NgayTao DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    NgayCapNhat DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    NgayHetHanNhap AS (DATEADD(HOUR, 24, NgayTao)) PERSISTED NOT NULL
);
GO

-- LichSuOTP
CREATE TABLE dbo.LichSuOTP
(
    MaOTP INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaHoSo INT NOT NULL,
    SoDienThoai VARCHAR(10) NOT NULL,
    OTPHash VARBINARY(32) NULL,
    ThoiGianGui DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    ThoiGianHetHan DATETIME2(3) NOT NULL,
    TrangThai VARCHAR(20) NOT NULL DEFAULT ('ChoXacThuc'),
    SoLanThu TINYINT NOT NULL DEFAULT (0),
    ThoiGianXacThuc DATETIME2(3) NULL,
    FOREIGN KEY (MaHoSo) REFERENCES dbo.HoSoDangKy (MaHoSo)
);
GO

-- LichSuXacThucEKYC
CREATE TABLE dbo.LichSuXacThucEKYC
(
    MaXacThuc INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaHoSo INT NOT NULL,
    LoaiXacThuc VARCHAR(20) NOT NULL,
    KetQua VARCHAR(12) NOT NULL,
    ConfidenceScore DECIMAL(5,2) NULL,
    LivenessPass BIT NULL,
    LanThu INT NOT NULL,
    PhienBanCCCD INT NOT NULL,
    MaLoi VARCHAR(50) NULL,
    ThoiGian DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    UNIQUE (MaHoSo, LanThu),
    FOREIGN KEY (MaHoSo) REFERENCES dbo.HoSoDangKy (MaHoSo)
);
GO

-- NhatKyKiemToan
CREATE TABLE dbo.NhatKyKiemToan
(
    MaNhatKy BIGINT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaHoSo INT NULL,
    HanhDong VARCHAR(100) NOT NULL,
    NguoiThucHien VARCHAR(30) NOT NULL,
    ThoiGian DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    ChiTiet NVARCHAR(MAX) NULL,
    FOREIGN KEY (MaHoSo) REFERENCES dbo.HoSoDangKy (MaHoSo)
);
GO

-- KhachHang
CREATE TABLE dbo.KhachHang
(
    MaKH INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaHoSo INT NOT NULL UNIQUE,
    MaCIF VARCHAR(20) NOT NULL UNIQUE,
    HoTen NVARCHAR(100) NOT NULL,
    SoCCCD VARCHAR(12) NOT NULL UNIQUE,
    NgaySinh DATE NOT NULL,
    GioiTinh NVARCHAR(10) NOT NULL,
    DiaChi NVARCHAR(255) NOT NULL,
    NgayHetHanCCCD DATE NOT NULL,
    SoDienThoai VARCHAR(10) NOT NULL,
    NgayTao DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    FOREIGN KEY (MaHoSo) REFERENCES dbo.HoSoDangKy (MaHoSo)
);
GO

-- TaiKhoan
CREATE TABLE dbo.TaiKhoan
(
    MaTaiKhoan INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    SoTaiKhoan VARCHAR(20) NOT NULL UNIQUE,
    MaKH INT NOT NULL UNIQUE,
    NgayMoTaiKhoan DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    TrangThai VARCHAR(20) NOT NULL DEFAULT ('HoatDong'),
    FOREIGN KEY (MaKH) REFERENCES dbo.KhachHang (MaKH)
);
GO

-- EBanking
CREATE TABLE dbo.EBanking
(
    MaEBanking INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
    MaKH INT NOT NULL UNIQUE,
    TenDangNhap VARCHAR(50) COLLATE Latin1_General_100_CI_AS NOT NULL UNIQUE,
    MatKhauHash VARCHAR(60) NOT NULL,
    MaPinHash VARCHAR(60) NOT NULL,
    NgayThietLap DATETIME2(3) NOT NULL DEFAULT (SYSUTCDATETIME()),
    FOREIGN KEY (MaKH) REFERENCES dbo.KhachHang (MaKH)
);
GO